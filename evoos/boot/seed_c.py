"""Emit C arrays of seed supervisors for the on-device evolution engine."""

from __future__ import annotations

import argparse
from pathlib import Path

from evoos.boot.pack import select_supervisor
from evoos.vm.instruction_set import Instr


def _emit(name: str, instrs: tuple[Instr, ...], origin: str) -> str:
    lines = [
        f"#define {name.upper()}_N {len(instrs)}",
        f'static const char {name}_origin[] = "{origin}";',
        f"static const EvoOSInstr {name}_code[{name.upper()}_N] = {{",
    ]
    for ins in instrs:
        lines.append(f"    {{{ins.op}, {ins.a}, {ins.b}, {ins.c}, {ins.imm}}},")
    lines.append("};")
    return "\n".join(lines)


def emit_header(kind: str = "evolved_open") -> str:
    live, live_o = select_supervisor(kind)
    s99, s99_o = select_supervisor("evolved_open")
    rr, rr_o = select_supervisor("persist_rr")
    return "\n".join(
        [
            "/* Generated by python -m evoos.boot.seed_c — do not edit. */",
            "#ifndef EVOOS_SUPERVISOR_SEED_H",
            "#define EVOOS_SUPERVISOR_SEED_H",
            "",
            '#include "evoos_vm.h"',
            "",
            _emit("seed_incumbent", live, live_o),
            "",
            _emit("seed_s99", s99, s99_o),
            "",
            _emit("seed_persist_rr", rr, rr_o),
            "",
            "#endif",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("-o", "--output", required=True)
    p.add_argument("--supervisor", default="evolved_open")
    args = p.parse_args(argv)
    Path(args.output).write_text(emit_header(args.supervisor))
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
