"""Emit a C header of guest programs the firmware loader may install.

Harvard code is not in data memory, so bytecode cannot load a new program.
Installing a catalogue entry is firmware (ROM BASIC-style), not a kernel exec.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from evoos.evaluator.workloads import (
    GUEST_SLOTS,
    guest_atk_load,
    guest_atk_store,
    guest_copyinc,
    guest_fill,
    guest_malicious_store,
    guest_max,
    guest_pressure,
    guest_route,
    guest_route_cons,
    guest_route_prod,
    guest_sum,
    guest_xor,
)
from evoos.vm.sandbox import GuestImage


def _programs() -> list[tuple[str, int, GuestImage]]:
    out: list[tuple[str, int, GuestImage]] = []
    victim = GUEST_SLOTS[1][0] + 2
    for slot in range(4):
        out.append(("sum", slot, guest_sum(slot, 8)))
        out.append(("fill", slot, guest_fill(slot, 5)))
        out.append(("xor", slot, guest_xor(slot, (3, 5, 7, 9, 1))))
        out.append(("copyinc", slot, guest_copyinc(slot, (4, 8, 2, 6))))
        out.append(("max", slot, guest_max(slot, (4, 17, 2, 9, 9))))
        out.append(("malicious", slot, guest_malicious_store(slot, victim)))
        out.append(("pressure", slot, guest_pressure(slot, 40)))
        out.append(("route", slot, guest_route(slot, 2 if slot != 1 else 3, 77)))
        out.append(("route_prod", slot, guest_route_prod(slot, 77)))
        out.append(("route_cons", slot, guest_route_cons(slot, 0)))
        out.append(("atk_store", slot, guest_atk_store(slot, 256)))
        out.append(("atk_load", slot, guest_atk_load(slot, 256)))
        out.append(("put", slot, _put(slot)))
        out.append(("get", slot, _get(slot)))
        out.append(("spin", slot, _spin(slot)))
    return out


def _put(slot: int) -> GuestImage:
    lo, hi = GUEST_SLOTS[slot]
    src = f"""
        MOVI r1, {lo}
        MOVI r2, 1
        SVC r2
        HALT
    """
    from evoos.vm.instruction_set import assemble as _asm

    return GuestImage(
        name="put",
        code=_asm(src),
        data_base=lo,
        data_bound=hi,
        init={lo: 7, lo + 1: 1, lo + 2: 123},
        expected={lo + 2: 123},
        needed_cycles=8,
    )


def _get(slot: int) -> GuestImage:
    lo, hi = GUEST_SLOTS[slot]
    src = f"""
        MOVI r1, {lo}
        MOVI r2, 2
        SVC r2
        HALT
    """
    from evoos.vm.instruction_set import assemble as _asm

    return GuestImage(
        name="get",
        code=_asm(src),
        data_base=lo,
        data_bound=hi,
        init={lo: 7, lo + 1: 1, lo + 2: 0},
        expected={},
        needed_cycles=8,
    )


def _spin(slot: int) -> GuestImage:
    lo, hi = GUEST_SLOTS[slot]
    src = """
    loop:
        JMP loop
    """
    from evoos.vm.instruction_set import assemble as _asm

    return GuestImage(
        name="spin",
        code=_asm(src),
        data_base=lo,
        data_bound=hi,
        init={lo: 1},
        expected={},
        needed_cycles=1,
    )


def _emit_instrs(name: str, code) -> str:
    lines = [f"static const EvoOSInstr {name}[] = {{"]
    for ins in code:
        lines.append(f"    {{{ins.op}, {ins.a}, {ins.b}, {ins.c}, {ins.imm}}},")
    lines.append("};")
    return "\n".join(lines)


def emit_header() -> str:
    progs = _programs()
    chunks: list[str] = [
        "/* Generated by python -m evoos.boot.catalogue — do not edit. */",
        "#ifndef EVOOS_GUEST_CATALOGUE_H",
        "#define EVOOS_GUEST_CATALOGUE_H",
        "",
        '#include "evoos_vm.h"',
        "",
        "#define CAT_MAX_INIT 32",
        "",
        "typedef struct {",
        "    const char *kind;",
        "    const char *name;",
        "    int slot;",
        "    int n_code;",
        "    const EvoOSInstr *code;",
        "    int32_t data_base;",
        "    int32_t data_bound;",
        "    int n_init;",
        "    int32_t init_addr[CAT_MAX_INIT];",
        "    int32_t init_val[CAT_MAX_INIT];",
        "} CatProg;",
        "",
    ]
    arrays = []
    inits = []
    for i, (kind, slot, g) in enumerate(progs):
        arr = f"cat_code_{i}"
        arrays.append(_emit_instrs(arr, g.code))
        ia = ", ".join(str(a) for a in g.init.keys()) or "0"
        iv = ", ".join(str(v) for v in g.init.values()) or "0"
        ninit = len(g.init)
        inits.append(
            "    {"
            f'"{kind}", "{g.name}", {slot}, {len(g.code)}, {arr}, '
            f"{g.data_base}, {g.data_bound}, {ninit}, "
            f"{{{ia}}}, {{{iv}}}"
            "},"
        )
    chunks.append("\n\n".join(arrays))
    chunks.append("")
    chunks.append(f"#define CAT_N {len(progs)}")
    chunks.append("static const CatProg CAT_PROGS[CAT_N] = {")
    chunks.extend(inits)
    chunks.append("};")
    chunks.append("")
    chunks.append("static int cat_find(const char *kind, int slot) {")
    chunks.append("    int i;")
    chunks.append("    for (i = 0; i < CAT_N; i++) {")
    chunks.append("        const char *k = CAT_PROGS[i].kind;")
    chunks.append("        const char *p = kind;")
    chunks.append("        if (CAT_PROGS[i].slot != slot) continue;")
    chunks.append("        while (*k && *p && *k == *p) { k++; p++; }")
    chunks.append("        if (*k == 0 && *p == 0) return i;")
    chunks.append("    }")
    chunks.append("    return -1;")
    chunks.append("}")
    chunks.append("")
    chunks.append("#endif")
    chunks.append("")
    return "\n".join(chunks)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("-o", "--output", required=True)
    args = p.parse_args(argv)
    Path(args.output).write_text(emit_header())
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
